import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';

export async function verifyPollEditor(browser, origin, { root, screenshots }) {
  const contexts = [], errors = [], password = 'poll-editor-password';
  const account = async username => {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: 'America/Los_Angeles' });
    contexts.push(context);
    const registered = await context.request.post(origin + '/api/v1/auth/register', { data: { username, password, email: username+'@example.com' } });
    assert.equal(registered.status(), 201);
    const id = (await registered.json()).data.id;
    assert.equal((await context.request.post(origin + '/api/v1/auth/login', { data: { username, password } })).status(), 200);
    const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
    return { context, page, id };
  };
  const local = milliseconds => new Date(milliseconds+8*3600_000).toISOString().slice(0,16);
  const heading = (page, name) => page.getByRole('heading', { name, exact: true, level: 1 }).waitFor();
  const ready = page => page.waitForFunction(() => document.querySelector('.poll-editor>fieldset') && !document.querySelector('.poll-editor>fieldset').disabled);
  const save = page => page.getByRole('button', { name: '保存草稿', exact: true });
  const add = page => page.getByRole('button', { name: '＋ 添加候选时间', exact: true });
  const shot = async (page, name) => {
    if (!screenshots) return;
    const directory = resolve(root, 'Docs/images/t16'); await mkdir(directory, { recursive: true });
    await page.screenshot({ path: resolve(directory, name+'.png'), fullPage: true });
  };
  const reply = (route, status, code, message, details = {}) => route.fulfill({ status, contentType: 'application/json', headers: { 'X-Request-ID': 'c07e357967c148068a4f9aa539c759e2' },
    body: JSON.stringify({ error: { code, message, details }, request_id: 'c07e357967c148068a4f9aa539c759e2' }) });
  try {
    const owner = await account('editor_owner'), member = await account('editor_member'), outsider = await account('editor_outside');
    const groupResponse = await owner.context.request.post(origin + '/api/v1/groups', { data: { name: '一起拼出好时间', description: '课程方案评审与下一步行动' } });
    const group = (await groupResponse.json()).data;
    assert.equal((await member.context.request.post(origin + '/api/v1/groups/join', { data: { invite_code: group.invite_code } })).status(), 200);
    const page = owner.page, groupUrl = origin+'/groups/'+group.id;
    await page.goto(groupUrl);
    await page.locator('.poll-list-card .button-link').click();
    await heading(page, '发起排期'); await ready(page);
    assert.equal(await page.getByRole('button', { name: '发布收集', exact: true }).isDisabled(), true);
    assert.equal(await page.locator('.field-error').count(), 0);
    assert.equal(await page.locator('#deadline-help').count(), 0);
    assert.equal(await page.locator('#poll-deadline').getAttribute('step'), '60');
    await save(page).click();
    assert.equal(await page.locator('.form-summary[role=alert]').evaluate(element => element === document.activeElement), true);
    await page.getByRole('button', { name: '主题需为1～100个字符。', exact: true }).click();
    assert.equal(await page.locator('#poll-title').evaluate(element => element === document.activeElement), true);
    const now = Math.floor(Date.now()/60000)*60000, deadline = now+3600_000, start = now+7200_000, end = now+10800_000;
    await page.locator('#poll-title').fill('课程方案评审');
    await page.locator('#poll-description').fill('梳理核心流程，确定下一步分工。');
    await page.locator('#poll-location').fill('计算机大楼2015A');
    await page.locator('#poll-deadline').fill(local(now-60000));
    await page.locator('#deadline-error').getByText('填写截止须在未来；最终以服务端时间为准。', { exact: true }).waitFor();
    await page.locator('#poll-deadline').fill(local(deadline));
    await save(page).click();
    await page.waitForURL(/\/polls\/\d+\/edit$/); await ready(page);
    const id = new URL(page.url()).pathname.split('/')[2];
    const savedEmpty = (await (await owner.context.request.get(origin+'/api/v1/polls/'+id)).json()).data;
    assert.equal(savedEmpty.response_deadline, new Date(deadline).toISOString());
    assert.deepEqual(savedEmpty.participants, []);
    assert.deepEqual(savedEmpty.slots, []);
    await page.getByRole('button', { name: '发布收集', exact: true }).click();
    await page.getByText('发布前请补全以下内容。', { exact: true }).waitFor();
    await page.getByRole('checkbox', { name: '选择 editor_owner', exact: true }).check();
    await page.getByRole('checkbox', { name: 'editor_owner 必到', exact: true }).check();
    await page.getByRole('checkbox', { name: '选择 editor_member', exact: true }).check();
    await add(page).click();
    await page.locator('.candidate-row').first().getByLabel('开始（北京时间）', { exact: true }).fill(local(start));
    await page.locator('.candidate-row').first().getByLabel('结束（北京时间）', { exact: true }).fill(local(end));
    assert.equal(await page.locator('.candidate-row input').first().getAttribute('step'), '60');
    await page.locator('.candidate-row').first().getByLabel('结束（北京时间）', { exact: true }).fill(local(start));
    await page.locator('.candidate-row .field-error').getByText('候选结束时间须晚于开始时间。', { exact: true }).waitFor();
    await page.locator('.candidate-row').first().getByLabel('结束（北京时间）', { exact: true }).fill(local(end));
    await page.locator('#poll-deadline').fill(local(start));
    await page.locator('#deadline-error').getByText('填写截止须早于每个候选开始时间。', { exact: true }).waitFor();
    await page.locator('#poll-deadline').fill(local(deadline));
    await add(page).click();
    await page.locator('.candidate-row').last().getByLabel('开始（北京时间）', { exact: true }).fill(local(start));
    await page.locator('.candidate-row').last().getByLabel('结束（北京时间）', { exact: true }).fill(local(end));
    await page.locator('.candidate-row .field-error').getByText('候选时段不能重复。', { exact: true }).waitFor();
    await save(page).click();
    await page.getByText('候选时段不能重复。', { exact: true }).first().waitFor();
    await page.getByRole('button', { name: '移除候选 2', exact: true }).click();
    await add(page).click();
    await page.locator('.candidate-row').last().getByLabel('开始（北京时间）', { exact: true }).fill(local(start+86400_000));
    await page.locator('.candidate-row').last().getByLabel('结束（北京时间）', { exact: true }).fill(local(end+86400_000));
    let saves = 0;
    await page.route(new RegExp(`/api/v1/polls/${id}$`), async route => {
      if (route.request().method() !== 'PUT') return route.continue();
      saves++; await new Promise(done => setTimeout(done, 400)); await route.continue();
    });
    await save(page).click();
    await page.waitForFunction(() => document.querySelector('.poll-editor>fieldset')?.disabled);
    await page.getByText(/^草稿已保存 ·/).waitFor();
    assert.equal(saves, 1);
    await page.unroute(new RegExp(`/api/v1/polls/${id}$`));
    await page.reload(); await ready(page);
    assert.equal(await page.locator('.candidate-row').count(), 2);
    assert.equal(await page.getByRole('checkbox', { name: 'editor_owner 必到', exact: true }).isChecked(), true);
    assert.equal(await page.locator('#poll-deadline').inputValue(), local(deadline));
    await shot(page, '03-editor');
    for (const width of [1440,1024,800,400]) {
      await page.setViewportSize({ width, height: 1000 });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Editor overflow ${width}`);
    }
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('#poll-title').fill('未保存的修改');
    assert.equal(await page.getByRole('button', { name: '发布收集', exact: true }).isDisabled(), true);
    page.once('dialog', dialog => dialog.dismiss());
    await page.locator('.back-link').click();
    assert.equal(await page.locator('#poll-title').inputValue(), '未保存的修改');
    page.once('dialog', dialog => dialog.accept());
    await page.locator('.back-link').click();
    await page.waitForURL(groupUrl);
    await page.locator('.poll-list-card').getByRole('link', { name: '课程方案评审', exact: true }).click();
    await page.waitForURL(origin+'/polls/'+id+'/edit'); await ready(page);
    assert.equal(await page.locator('#poll-title').inputValue(), '课程方案评审');
    page.once('dialog', dialog => dialog.dismiss());
    await page.getByRole('button', { name: '发布收集', exact: true }).click();
    assert.equal((await (await owner.context.request.get(origin+'/api/v1/polls/'+id)).json()).data.status, 'DRAFT');
    await page.route(`**/api/v1/polls/${id}/open`, route => reply(route, 422, 'VALIDATION_ERROR', '请核对截止时间。', { fields: [{ location: ['body','response_deadline'] }] }));
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: '发布收集', exact: true }).click();
    await page.getByText('请核对截止时间。', { exact: true }).waitFor();
    assert.equal(await page.locator('#poll-deadline').getAttribute('aria-invalid'), 'true');
    assert.equal(await page.locator('#poll-title').inputValue(), '课程方案评审');
    await page.unroute(`**/api/v1/polls/${id}/open`);
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: '发布收集', exact: true }).click();
    await heading(page, '排期详情');
    await page.getByText('排期已发布，候选时间和参与者已冻结。', { exact: true }).waitFor();
    assert.equal(await page.locator('.poll-editor').count(), 0);
    await shot(page, '04-published');
    await member.page.goto(origin+'/polls/'+id+'/edit'); await heading(member.page, '排期详情');
    assert.equal(await member.page.locator('.poll-editor').count(), 0);
    await member.page.goto(origin+`/groups/${group.id}/polls/new`);
    await member.page.getByRole('heading', { name: '只有负责人可以发起排期', exact: true }).waitFor();
    assert.equal(await member.page.locator('.poll-editor').count(), 0);
    await outsider.page.goto(origin+'/polls/'+id+'/edit');
    await outsider.page.getByRole('heading', { name: '未找到可访问的排期或小组', exact: true }).waitFor();
    assert.equal(await outsider.page.getByText('课程方案评审', { exact: true }).count(), 0);

    // Lost create response: preserve input, failed reconciliation can be retried, no automatic POST.
    await page.goto(origin+`/groups/${group.id}/polls/new`); await ready(page);
    await page.locator('#poll-title').fill('待核对的草稿'); await page.locator('#poll-deadline').fill(local(deadline));
    let creates = 0;
    await page.route(`**/api/v1/groups/${group.id}/polls`, async route => {
      creates++; const response = await route.fetch(); await route.fulfill({ response, body: '{damaged' });
    });
    await save(page).click();
    await page.getByRole('button', { name: '核对服务端结果', exact: true }).waitFor();
    assert.equal(creates, 1);
    assert.equal(await save(page).isDisabled(), true);
    await page.route(new RegExp(`/api/v1/groups/${group.id}/polls\\?`), route => route.abort());
    await page.getByRole('button', { name: '核对服务端结果', exact: true }).click();
    await page.getByRole('heading', { name: '排期信息暂时无法读取', exact: true }).waitFor();
    assert.equal(await page.locator('#poll-title').inputValue(), '待核对的草稿');
    await page.unroute(new RegExp(`/api/v1/groups/${group.id}/polls\\?`));
    await page.getByRole('button', { name: '重试读取排期', exact: true }).click();
    await page.getByRole('checkbox', { name: '我已核对，仍需再次创建（可能产生重复排期）', exact: true }).waitFor();
    assert.equal(await save(page).isDisabled(), true);
    await page.unroute(`**/api/v1/groups/${group.id}/polls`);
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('link', { name: '待核对的草稿 · 草稿', exact: true }).click();
    await page.waitForURL(/\/polls\/\d+\/edit$/); await ready(page);
    const secondId = new URL(page.url()).pathname.split('/')[2];
    await page.locator('#poll-title').fill('核对后已保存的内容');
    let updates = 0;
    await page.route(new RegExp(`/api/v1/polls/${secondId}$`), async route => {
      if (route.request().method() !== 'PUT') return route.continue();
      updates++; const response = await route.fetch(); await route.fulfill({ response, body: '{damaged' });
    });
    await save(page).click();
    await page.getByRole('button', { name: '核对服务端结果', exact: true }).click();
    await page.getByText('已核对服务端，当前草稿内容已保存。', { exact: true }).waitFor();
    assert.equal(updates, 1);
    await page.unroute(new RegExp(`/api/v1/polls/${secondId}$`));
    await page.locator('#poll-title').fill('保留在本页的改动');
    await page.route(new RegExp(`/api/v1/polls/${secondId}$`), route => route.request().method() === 'PUT' ? route.abort() : route.continue());
    await save(page).click();
    await page.getByRole('button', { name: '核对服务端结果', exact: true }).click();
    await page.getByRole('checkbox', { name: '我已核对，确认使用本页输入再次保存', exact: true }).waitFor();
    assert.equal(await page.locator('#poll-title').inputValue(), '保留在本页的改动');
    assert.equal(await save(page).isDisabled(), true);
    await page.unroute(new RegExp(`/api/v1/polls/${secondId}$`));
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: '载入服务端版本', exact: true }).click();
    await ready(page);
    assert.equal(await page.locator('#poll-title').inputValue(), '核对后已保存的内容');
    // External publication during an edit freezes server data and keeps local changes visibly separate.
    await page.getByRole('checkbox', { name: '选择 editor_owner', exact: true }).check();
    await add(page).click();
    await page.locator('.candidate-row').first().getByLabel('开始（北京时间）', { exact: true }).fill(local(start));
    await page.locator('.candidate-row').first().getByLabel('结束（北京时间）', { exact: true }).fill(local(end));
    await save(page).click(); await page.getByText(/^草稿已保存 ·/).waitFor();
    await page.locator('#poll-title').fill('本页未保存的独立输入');
    assert.equal((await owner.context.request.post(origin+`/api/v1/polls/${secondId}/open`, { data: {} })).status(), 200);
    await save(page).click();
    await page.getByRole('button', { name: '核对服务端结果', exact: true }).click();
    await heading(page, '排期详情');
    assert.equal(await page.locator('#poll-title').inputValue(), '本页未保存的独立输入');
    await page.waitForFunction(() => document.querySelector('.poll-editor>fieldset')?.disabled);
    assert.equal(await page.locator('#poll-title').isDisabled(), true);
    assert.match(await page.locator('.poll-readonly h2').textContent(), /核对后已保存的内容/);
    page.once('dialog', dialog => dialog.accept());
    await page.locator('.back-link').click(); await page.waitForURL(groupUrl);
    await page.locator('.poll-list-card').getByRole('link', { name: '核对后已保存的内容', exact: true }).waitFor();
    const third = await owner.context.request.post(origin+`/api/v1/groups/${group.id}/polls`, { data: { title: '发布结果核对', response_deadline: new Date(deadline).toISOString(),
      participants: [{ user_id: owner.id, importance: 'REQUIRED' }], slots: [{ start_at: new Date(start).toISOString(), end_at: new Date(end).toISOString() }] } });
    assert.equal(third.status(), 201);
    const thirdId = (await third.json()).data.id;
    await page.goto(origin+`/polls/${thirdId}/edit`); await ready(page);
    let publications = 0;
    await page.route(`**/api/v1/polls/${thirdId}/open`, async route => {
      publications++; const response = await route.fetch(); await route.fulfill({ response, body: '{damaged' });
    });
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: '发布收集', exact: true }).click();
    await page.getByRole('button', { name: '核对服务端结果', exact: true }).click();
    await heading(page, '排期详情');
    await page.getByText('已读取最新状态：收集中。', { exact: true }).waitFor();
    assert.equal(publications, 1);
    assert.equal(await page.locator('.poll-editor').count(), 0);
    await page.unroute(`**/api/v1/polls/${thirdId}/open`);
    await page.locator('.back-link').click(); await page.waitForURL(groupUrl);
    await page.locator('.poll-list-card').getByRole('link', { name: '发布结果核对', exact: true }).waitFor();
    await shot(page, '05-group-polls');
    // Expiry redirect must not be blocked by the draft leave guard.
    await page.locator('.poll-list-card .button-link').click(); await ready(page);
    await page.locator('#poll-title').fill('账号甲的排期输入'); await page.locator('#poll-deadline').fill(local(deadline));
    await owner.context.request.post(origin+'/api/v1/auth/logout', { data: {} });
    await save(page).click();
    await page.getByRole('heading', { name: '欢迎回来', exact: true }).waitFor();
    assert.match(await page.locator('.auth-note').textContent(), /未提交的输入已清空/);
    await page.locator('#username').fill('editor_outside'); await page.locator('#password').fill(password);
    await page.locator('button[type=submit]').click();
    await page.getByRole('heading', { name: '未找到可访问的排期或小组', exact: true }).waitFor();
    assert.equal(await page.locator('#poll-title').count(), 0);
    assert.equal(await page.evaluate(() => localStorage.length+sessionStorage.length), 0);
    assert.deepEqual(errors, []);
    console.log('PASS T16 UI: group entry, Beijing dates under another browser timezone, draft/required members/candidates, validation, one save, reload/leave, publish/readonly, member/outside rights, lost create/update responses, failed reconciliation recovery, external freeze, expiry/new account and 4 widths.');
  } catch (error) {
    console.error('T16 failure', error, 'Page errors:', errors);
    for (const context of contexts) for (const page of context.pages()) if (await page.locator('main').count()) console.error('T16 diagnostic', page.url(), (await page.locator('main').innerText({ timeout: 1000 })).slice(0,2000));
    throw error;
  } finally { for (const context of contexts) await context.close(); }
}
