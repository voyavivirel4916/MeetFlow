from sqlalchemy import (Boolean, CheckConstraint, Column, ForeignKey, ForeignKeyConstraint, Index,
                        Integer, MetaData, Table, Text, UniqueConstraint, text)

# Implemented schemas only. Tasks arrive with later tasks.
metadata = MetaData()
users = Table('users', metadata,
    Column('id', Integer, primary_key=True),
    Column('username', Text, nullable=False, unique=True),
    Column('email', Text, nullable=False, unique=True),
    Column('password_hash', Text, nullable=False),
    Column('created_at', Integer, nullable=False),
    CheckConstraint('id > 0', name='ck_users_id'),
    CheckConstraint("length(username) BETWEEN 3 AND 32 AND username = lower(trim(username)) AND username NOT GLOB '*[^a-z0-9_]*'", name='ck_users_username'),
    CheckConstraint('length(email) BETWEEN 1 AND 254 AND email = lower(trim(email))', name='ck_users_email'))
sessions = Table('sessions', metadata,
    Column('id', Integer, primary_key=True),
    Column('user_id', Integer, ForeignKey('users.id', ondelete='RESTRICT'), nullable=False),
    Column('token_hash', Text, nullable=False, unique=True),
    Column('created_at', Integer, nullable=False),
    Column('expires_at', Integer, nullable=False),
    Column('revoked_at', Integer),
    CheckConstraint('id > 0', name='ck_sessions_id'),
    CheckConstraint("length(token_hash) = 64 AND token_hash NOT GLOB '*[^0-9a-f]*'", name='ck_sessions_hash'),
    CheckConstraint('expires_at > created_at', name='ck_sessions_expiry'))
Index('ix_sessions_expires_at', sessions.c.expires_at)
groups = Table('groups', metadata,
    Column('id', Integer, primary_key=True),
    Column('name', Text, nullable=False),
    Column('description', Text, nullable=False, server_default=text("''")),
    Column('owner_id', Integer, ForeignKey('users.id', ondelete='RESTRICT'), nullable=False),
    Column('invite_code', Text, nullable=False, unique=True),
    Column('invite_enabled', Boolean(create_constraint=True, name='ck_groups_invite_enabled'), nullable=False, server_default='1'),
    Column('created_at', Integer, nullable=False),
    Column('updated_at', Integer, nullable=False),
    CheckConstraint('id > 0', name='ck_groups_id'),
    CheckConstraint('length(name) BETWEEN 1 AND 100', name='ck_groups_name'),
    CheckConstraint('length(description) <= 10000', name='ck_groups_description'),
    CheckConstraint("length(invite_code) = 12 AND invite_code NOT GLOB '*[^A-Z0-9]*'", name='ck_groups_invite_code'))
group_members = Table('group_members', metadata,
    Column('group_id', Integer, ForeignKey('groups.id', ondelete='RESTRICT'), primary_key=True),
    Column('user_id', Integer, ForeignKey('users.id', ondelete='RESTRICT'), primary_key=True),
    Column('joined_at', Integer, nullable=False))
Index('ix_group_members_user_id', group_members.c.user_id)

polls = Table('polls', metadata,
    Column('id', Integer, primary_key=True),
    Column('group_id', Integer, ForeignKey('groups.id', ondelete='RESTRICT'), nullable=False),
    Column('title', Text, nullable=False),
    Column('description', Text, nullable=False, server_default=text("''")),
    Column('location', Text, nullable=False, server_default=text("''")),
    Column('response_deadline', Integer, nullable=False),
    Column('status', Text, nullable=False, server_default=text("'DRAFT'")),
    Column('created_at', Integer, nullable=False),
    Column('updated_at', Integer, nullable=False),
    CheckConstraint('id > 0', name='ck_polls_id'),
    CheckConstraint('length(title) BETWEEN 1 AND 100', name='ck_polls_title'),
    CheckConstraint('length(description) <= 10000', name='ck_polls_description'),
    CheckConstraint('length(location) <= 200', name='ck_polls_location'),
    CheckConstraint("status IN ('DRAFT','OPEN','CLOSED','CONFIRMED','CANCELLED')", name='ck_polls_status'),
    CheckConstraint("typeof(response_deadline) = 'integer' AND typeof(created_at) = 'integer' AND typeof(updated_at) = 'integer'", name='ck_polls_times'),
    UniqueConstraint('id', 'group_id', name='uq_polls_id_group'))
Index('ix_polls_group_status', polls.c.group_id, polls.c.status)

participants = Table('participants', metadata,
    Column('poll_id', Integer, primary_key=True),
    Column('group_id', Integer, nullable=False),
    Column('user_id', Integer, primary_key=True),
    Column('importance', Text, nullable=False),
    Column('submitted_at', Integer),
    ForeignKeyConstraint(['poll_id', 'group_id'], ['polls.id', 'polls.group_id'], ondelete='RESTRICT', name='fk_participants_poll_group'),
    ForeignKeyConstraint(['group_id', 'user_id'], ['group_members.group_id', 'group_members.user_id'], ondelete='RESTRICT', name='fk_participants_group_member'),
    CheckConstraint("importance IN ('REQUIRED','NORMAL')", name='ck_participants_importance'),
    CheckConstraint("submitted_at IS NULL OR typeof(submitted_at) = 'integer'", name='ck_participants_submitted_at'))

slots = Table('slots', metadata,
    Column('id', Integer, primary_key=True),
    Column('poll_id', Integer, ForeignKey('polls.id', ondelete='RESTRICT'), nullable=False),
    Column('start_at', Integer, nullable=False),
    Column('end_at', Integer, nullable=False),
    CheckConstraint('id > 0', name='ck_slots_id'),
    CheckConstraint('start_at < end_at', name='ck_slots_order'),
    CheckConstraint("typeof(start_at) = 'integer' AND typeof(end_at) = 'integer'", name='ck_slots_times'),
    UniqueConstraint('poll_id', 'start_at', 'end_at', name='uq_slots_poll_time'),
    UniqueConstraint('poll_id', 'id', name='uq_slots_poll_id'))

votes = Table('votes', metadata,
    Column('poll_id', Integer, nullable=False),
    Column('slot_id', Integer, primary_key=True),
    Column('user_id', Integer, primary_key=True),
    Column('availability', Text, nullable=False),
    Column('updated_at', Integer, nullable=False),
    ForeignKeyConstraint(['poll_id', 'slot_id'], ['slots.poll_id', 'slots.id'], ondelete='RESTRICT', name='fk_votes_poll_slot'),
    ForeignKeyConstraint(['poll_id', 'user_id'], ['participants.poll_id', 'participants.user_id'], ondelete='RESTRICT', name='fk_votes_poll_participant'),
    CheckConstraint("availability IN ('AVAILABLE','MAYBE','UNAVAILABLE')", name='ck_votes_availability'),
    CheckConstraint("typeof(updated_at) = 'integer'", name='ck_votes_updated_at'))
Index('ix_votes_poll_user', votes.c.poll_id, votes.c.user_id)

meetings = Table('meetings', metadata,
    Column('id', Integer, primary_key=True),
    Column('poll_id', Integer, nullable=False, unique=True),
    Column('group_id', Integer, nullable=False),
    Column('selected_slot_id', Integer, nullable=False),
    Column('title', Text, nullable=False),
    Column('location', Text, nullable=False),
    Column('start_at', Integer, nullable=False),
    Column('end_at', Integer, nullable=False),
    Column('selection_reason', Text, nullable=False, server_default=text("''")),
    Column('agenda', Text, nullable=False, server_default=text("''")),
    Column('minutes', Text, nullable=False, server_default=text("''")),
    Column('created_at', Integer, nullable=False),
    Column('updated_at', Integer, nullable=False),
    ForeignKeyConstraint(['poll_id', 'group_id'], ['polls.id', 'polls.group_id'], ondelete='RESTRICT', name='fk_meetings_poll_group'),
    ForeignKeyConstraint(['poll_id', 'selected_slot_id'], ['slots.poll_id', 'slots.id'], ondelete='RESTRICT', name='fk_meetings_poll_slot'),
    CheckConstraint('id > 0', name='ck_meetings_id'),
    CheckConstraint('length(title) BETWEEN 1 AND 100', name='ck_meetings_title'),
    CheckConstraint('length(location) <= 200', name='ck_meetings_location'),
    CheckConstraint('start_at < end_at', name='ck_meetings_order'),
    CheckConstraint('length(selection_reason) <= 500', name='ck_meetings_selection_reason'),
    CheckConstraint('length(agenda) <= 10000 AND length(minutes) <= 10000', name='ck_meetings_notes'),
    CheckConstraint("typeof(start_at) = 'integer' AND typeof(end_at) = 'integer' AND typeof(created_at) = 'integer' AND typeof(updated_at) = 'integer'", name='ck_meetings_times'))
Index('ix_meetings_group_id', meetings.c.group_id)
Index('uq_meetings_id_group', meetings.c.id, meetings.c.group_id, unique=True)

tasks = Table('tasks', metadata,
    Column('id', Integer, primary_key=True),
    Column('meeting_id', Integer, nullable=False),
    Column('group_id', Integer, nullable=False),
    Column('creator_id', Integer, ForeignKey('users.id', ondelete='RESTRICT'), nullable=False),
    Column('assignee_id', Integer, nullable=False),
    Column('title', Text, nullable=False),
    Column('description', Text, nullable=False, server_default=text("''")),
    Column('due_at', Integer, nullable=False),
    Column('status', Text, nullable=False, server_default=text("'TODO'")),
    Column('completed_at', Integer),
    Column('client_request_id', Text, nullable=False),
    Column('created_at', Integer, nullable=False),
    Column('updated_at', Integer, nullable=False),
    UniqueConstraint('creator_id', 'client_request_id', name='uq_tasks_creator_request'),
    ForeignKeyConstraint(['meeting_id', 'group_id'], ['meetings.id', 'meetings.group_id'], ondelete='RESTRICT', name='fk_tasks_meeting_group'),
    ForeignKeyConstraint(['group_id', 'assignee_id'], ['group_members.group_id', 'group_members.user_id'], ondelete='RESTRICT', name='fk_tasks_assignee_member'),
    CheckConstraint('id > 0', name='ck_tasks_id'),
    CheckConstraint('length(title) BETWEEN 1 AND 100', name='ck_tasks_title'),
    CheckConstraint('length(description) <= 10000', name='ck_tasks_description'),
    CheckConstraint("status IN ('TODO','IN_PROGRESS','DONE')", name='ck_tasks_status'),
    CheckConstraint("(status = 'DONE' AND completed_at IS NOT NULL) OR (status != 'DONE' AND completed_at IS NULL)", name='ck_tasks_completion'),
    CheckConstraint('due_at > created_at', name='ck_tasks_deadline'),
    CheckConstraint("typeof(due_at) = 'integer' AND typeof(created_at) = 'integer' AND typeof(updated_at) = 'integer' AND (completed_at IS NULL OR typeof(completed_at) = 'integer')", name='ck_tasks_times'),
    CheckConstraint("length(client_request_id) = 36 AND substr(client_request_id,9,1) = '-' AND substr(client_request_id,14,1) = '-' AND substr(client_request_id,19,1) = '-' AND substr(client_request_id,24,1) = '-' AND length(replace(client_request_id,'-','')) = 32 AND replace(client_request_id,'-','') NOT GLOB '*[^0-9a-f]*'", name='ck_tasks_request_id'))
Index('ix_tasks_assignee_status_due', tasks.c.assignee_id, tasks.c.status, tasks.c.due_at)
Index('ix_tasks_group_created', tasks.c.group_id, tasks.c.created_at)
